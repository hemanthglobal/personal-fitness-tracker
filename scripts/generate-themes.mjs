/*
 * Builds the Material 3 colour themes from seed colours with Google's material-color-utilities.
 *   node scripts/generate-themes.mjs
 * Writes src/styles/themes.css (the app's tokens per palette and mode) and
 * src/data/theme-swatches.ts (preview colours for the Appearance settings).
 * "classic" is the original hand-made theme in main.css and is not generated.
 */
import { writeFileSync } from "node:fs";
import { register } from "node:module";

// The package uses extensionless ESM imports, which Node can't resolve on its own: add ".js".
register(`data:text/javascript,${encodeURIComponent(`
export async function resolve(spec, ctx, next) {
  try { return await next(spec, ctx); }
  catch (e) { if (spec.startsWith(".") && !spec.endsWith(".js")) return next(spec + ".js", ctx); throw e; }
}`)}`);
const { argbFromHex, hexFromArgb, Hct, MaterialDynamicColors: C, SchemeTonalSpot, SchemeVibrant } = await import("@material/material-color-utilities");

/** id → seed colour, scheme variant, contrast level (0 standard, 1 high), modes offered. */
const PALETTES = {
  violet: { seed: "#6750A4", Scheme: SchemeTonalSpot, contrast: 0, modes: ["light", "dark"] },
  ocean: { seed: "#00696E", Scheme: SchemeTonalSpot, contrast: 0, modes: ["light", "dark"] },
  forest: { seed: "#386A20", Scheme: SchemeTonalSpot, contrast: 0, modes: ["light", "dark"] },
  ember: { seed: "#C62828", Scheme: SchemeVibrant, contrast: 0, modes: ["light", "dark"] },
  midnight: { seed: "#3D5AFE", Scheme: SchemeTonalSpot, contrast: 0, modes: ["dark"] },
  contrast: { seed: "#0B57D0", Scheme: SchemeTonalSpot, contrast: 1, modes: ["light", "dark"] },
};

const hex = (argb) => hexFromArgb(argb).toLowerCase();

function tokens(id, p, dark) {
  const s = new p.Scheme(Hct.fromInt(argbFromHex(p.seed)), dark, p.contrast);
  const get = (c) => hex(c.getArgb(s));
  const n = (t) => hex(s.neutralPalette.tone(t));
  const nv = (t) => hex(s.neutralVariantPalette.tone(t));
  const primary = C.primary.getArgb(s);
  const pressTone = Hct.fromInt(primary).tone + (dark ? -8 : -8);
  const high = p.contrast > 0;
  const t = {
    bg: dark ? (id === "midnight" ? n(3) : get(C.surface)) : get(C.surfaceContainer),
    surface: dark ? get(C.surfaceContainerLow) : get(C.surfaceContainerLowest),
    "surface-2": dark ? get(C.surfaceContainerHigh) : get(C.surfaceContainer),
    "surface-3": dark ? get(C.surfaceContainerHighest) : get(C.surfaceContainerHigh),
    text: get(C.onSurface),
    "text-2": get(C.onSurfaceVariant),
    muted: high ? get(C.onSurfaceVariant) : dark ? nv(70) : nv(40),
    border: high ? get(C.outline) : get(C.outlineVariant),
    "border-strong": high ? get(C.onSurfaceVariant) : dark ? nv(40) : nv(68),
    primary: hex(primary),
    "primary-press": hex(s.primaryPalette.tone(Math.max(0, Math.min(100, pressTone)))),
    // The app puts normal text on primary-soft, so high contrast keeps it a pale (or deep) tint.
    "primary-soft": high ? hex(s.primaryPalette.tone(dark ? 20 : 92)) : get(C.primaryContainer),
    "on-primary": get(C.onPrimary),
    "accent-text": get(C.primary),
    ink: dark ? n(12) : n(10),
    "ink-2": dark ? n(20) : n(17),
    "on-ink": n(95),
    "on-ink-muted": nv(70),
  };
  return t;
}

const block = (sel, t, mode) =>
  `${sel} {\n${Object.entries(t).map(([k, v]) => `  --${k}: ${v};`).join("\n")}\n  color-scheme: ${mode};\n}\n`;

let css = `/* GENERATED by scripts/generate-themes.mjs from Material 3 seed colours. Do not edit by hand. */\n\n`;
const swatches = {};
for (const [id, p] of Object.entries(PALETTES)) {
  const light = p.modes.includes("light") ? tokens(id, p, false) : null;
  const dark = tokens(id, p, true);
  if (light) {
    css += block(`:root[data-palette="${id}"]`, light, "light");
    css += block(`:root[data-palette="${id}"][data-mode="dark"]`, dark, "dark");
  } else {
    css += block(`:root[data-palette="${id}"], :root[data-palette="${id}"][data-mode="dark"]`, dark, "dark");
  }
  css += "\n";
  const sw = (t) => ({ bg: t.bg, surface: t.surface, primary: t.primary, soft: t["primary-soft"] });
  swatches[id] = { light: sw(light ?? dark), dark: sw(dark) };
}

writeFileSync(new URL("../src/styles/themes.css", import.meta.url), css);
writeFileSync(
  new URL("../src/data/theme-swatches.ts", import.meta.url),
  `/* GENERATED by scripts/generate-themes.mjs. Preview colours for the Appearance settings. */\n` +
    `export const SWATCHES: Record<string, Record<"light" | "dark", { bg: string; surface: string; primary: string; soft: string }>> = ${JSON.stringify(swatches, null, 2)};\n`,
);
console.log(`Wrote ${Object.keys(PALETTES).length} palettes.`);
