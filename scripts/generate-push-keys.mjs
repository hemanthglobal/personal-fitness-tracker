// Generates everything the reminders need, using only Node's built-in crypto:
//   - a VAPID key pair (Web Push identity of your app)
//   - a random CRON_SECRET (lets the scheduler call the function)
// Writes them to .env.push.local (git-ignored). Run:  npm run push:keys
import { generateKeyPairSync, randomBytes } from "node:crypto";
import { existsSync, writeFileSync } from "node:fs";

const out = ".env.push.local";
if (existsSync(out) && !process.argv.includes("--force")) {
  console.log(`${out} already exists. Keeping it (use --force to replace; replacing breaks existing subscriptions).`);
  process.exit(0);
}

const { publicKey, privateKey } = generateKeyPairSync("ec", { namedCurve: "prime256v1" });
const pub = publicKey.export({ format: "jwk" });
const priv = privateKey.export({ format: "jwk" });
const b64 = (s) => Buffer.from(s, "base64url");
// Uncompressed P-256 public key: 0x04 || X || Y, base64url — what browsers and web-push expect.
const vapidPublic = Buffer.concat([Buffer.from([4]), b64(pub.x), b64(pub.y)]).toString("base64url");
const vapidPrivate = priv.d;
const cronSecret = randomBytes(24).toString("base64url");

writeFileSync(out, [
  "# Generated by scripts/generate-push-keys.mjs. NEVER commit this file.",
  "# Public (browser, GitHub Variables, .env.local):",
  `VITE_VAPID_PUBLIC_KEY=${vapidPublic}`,
  "",
  "# Supabase → Edge Functions → Secrets (server only):",
  `VAPID_PUBLIC_KEY=${vapidPublic}`,
  `VAPID_PRIVATE_KEY=${vapidPrivate}`,
  "VAPID_SUBJECT=mailto:you@example.com",
  `CRON_SECRET=${cronSecret}`,
  "",
].join("\n"));

console.log(`Wrote ${out}. Open it and follow docs/REMINDERS_SETUP.md.`);
