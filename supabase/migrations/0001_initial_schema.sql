-- 0001 — Initial schema for the personal 60-day fitness tracker.
--
-- Design notes
-- * The programme definition (exercises, sets, reps, supersets) lives in the frontend
--   (src/data/workout-data.ts). The database stores user state only.
-- * Every user-owned table carries user_id. Child tables reference their parent with a
--   COMPOSITE foreign key (parent_id, user_id) -> parent(id, user_id). Combined with RLS
--   (user_id = auth.uid()), a user cannot attach rows to someone else's parent row, even
--   by guessing a UUID.
-- * Weights on exercise sets are stored in kilograms (weight_kg). Unit is a display preference.

-- ---------------------------------------------------------------------------
-- Helpers
-- ---------------------------------------------------------------------------
create or replace function public.set_updated_at()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  new.updated_at := now();
  return new;
end;
$$;

